"""CI reporter — formats eval results as markdown for PR comments."""


def format_markdown_report(summary: dict, baseline: dict | None = None) -> str:
    """Format eval summary as a markdown table for CI.

    Args:
        summary: Output from aggregate_results()
        baseline: Optional baseline scores to compute diff

    Returns:
        Markdown-formatted report
    """
    lines = [
        "## Agent Evaluation Report",
        "",
        "| Category | Cases | Overall | Correctness | Citations | Confidence | Hallucination | Actions | Tool Coverage | Routing |",
        "|----------|-------|---------|-------------|-----------|------------|---------------|---------|---------------|---------|",
    ]

    categories = [k for k in sorted(summary.keys()) if not k.startswith("_")]
    for cat in categories:
        s = summary[cat]
        diff_str = ""
        if baseline and cat in baseline:
            diff = s["avg_overall"] - baseline[cat].get("avg_overall", 0)
            diff_str = f" ({'+' if diff >= 0 else ''}{diff:.3f})"

        lines.append(
            f"| {cat} | {s['count']} | "
            f"{_score_cell(s['avg_overall'])}{diff_str} | "
            f"{_score_cell(s['avg_correctness'])} | "
            f"{_score_cell(s['avg_citations'])} | "
            f"{_score_cell(s['avg_confidence'])} | "
            f"{_score_cell(s['avg_hallucination'])} | "
            f"{_score_cell(s['avg_actions'])} | "
            f"{_score_cell(s['avg_tool_coverage'])} | "
            f"{_score_cell(s['routing_accuracy'])} |"
        )

    if "_overall" in summary:
        o = summary["_overall"]
        lines.append(
            f"| **OVERALL** | {o['count']} | "
            f"**{o['avg_overall']:.3f}** | - | - | - | - | - | "
            f"{o['avg_tool_coverage']:.3f} | "
            f"{o['routing_accuracy']:.3f} |"
        )

    lines.extend([
        "",
        "### Score Thresholds",
        "- Overall >= 0.70: PASS",
        "- Correctness >= 0.60: PASS",
        "- Hallucination >= 0.80: PASS (1.0 = no hallucinations)",
        "",
        "_Generated by PrimeEV Factory Floor Agent eval system_",
    ])

    return "\n".join(lines)


def check_thresholds(summary: dict) -> tuple[bool, list[str]]:
    """Check if eval results meet minimum thresholds.

    Returns:
        Tuple of (all_passed, list of failure messages)
    """
    failures = []
    thresholds = {
        "avg_overall": 0.70,
        "avg_correctness": 0.60,
        "avg_hallucination": 0.80,
    }

    for cat, scores in summary.items():
        if cat.startswith("_"):
            continue
        for metric, threshold in thresholds.items():
            if metric in scores and scores[metric] < threshold:
                failures.append(
                    f"{cat}/{metric}: {scores[metric]:.3f} < {threshold:.3f}"
                )

    return len(failures) == 0, failures


def _score_cell(score: float) -> str:
    """Format a score as a colored markdown cell."""
    if score >= 0.80:
        return f"{score:.3f}"
    elif score >= 0.60:
        return f"**{score:.3f}**"
    else:
        return f"~~{score:.3f}~~"
